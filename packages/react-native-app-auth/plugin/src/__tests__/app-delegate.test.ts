import { applyExpoAppDelegatePatch } from '../ios/app-delegate';

const expo56AppDelegate = `internal import Expo
import React
import ReactAppDependencyProvider

@main
class AppDelegate: ExpoAppDelegate {
  var window: UIWindow?

  var reactNativeDelegate: ExpoReactNativeFactoryDelegate?
  var reactNativeFactory: RCTReactNativeFactory?

  public override func application(
    _ app: UIApplication,
    open url: URL,
    options: [UIApplication.OpenURLOptionsKey: Any] = [:]
  ) -> Bool {
    return super.application(app, open: url, options: options) || RCTLinkingManager.application(app, open: url, options: options)
  }
  public override func application(
    _ application: UIApplication,
    continue userActivity: NSUserActivity,
    restorationHandler: @escaping ([UIUserActivityRestoring]?) -> Void
  ) -> Bool {
    return super.application(application, continue: userActivity, restorationHandler: restorationHandler)
  }
}`;

const reactNativeDelegate = `class ReactNativeDelegate: ExpoReactNativeFactoryDelegate {
  // Extension point for config-plugins

  override func sourceURL(for bridge: RCTBridge) -> URL? {
    // needed to return the correct URL for expo-dev-client.
    bridge.bundleURL ?? bundleURL()
  }

  override func bundleURL() -> URL? {
#if DEBUG
    return RCTBundleURLProvider.sharedSettings().jsBundleURL(forBundleRoot: ".expo/.virtual-metro-entry")
#else
    return Bundle.main.url(forResource: "main", withExtension: "jsbundle")
#endif
  }
}`;

// Generated by Expo SDK 57 prebuild with expo-build-properties ios.enableSceneSupport.
const expo57AppDelegate = `internal import Expo
import React
import ReactAppDependencyProvider

@main
class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider {
  var window: UIWindow?

  var reactNativeDelegate: ExpoReactNativeFactoryDelegate?
  var reactNativeFactory: RCTReactNativeFactory?

  public override func application(
    _ application: UIApplication,
    didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]? = nil
  ) -> Bool {
    let delegate = ReactNativeDelegate()
    let factory = ExpoReactNativeFactory(delegate: delegate)
    delegate.dependencyProvider = RCTAppDependencyProvider()

    reactNativeDelegate = delegate
    reactNativeFactory = factory

    return super.application(application, didFinishLaunchingWithOptions: launchOptions)
  }

  // Linking API
  public override func application(
    _ app: UIApplication,
    open url: URL,
    options: [UIApplication.OpenURLOptionsKey: Any] = [:]
  ) -> Bool {
    return super.application(app, open: url, options: options) || RCTLinkingManager.application(app, open: url, options: options)
  }

  // Universal Links
  public override func application(
    _ application: UIApplication,
    continue userActivity: NSUserActivity,
    restorationHandler: @escaping ([UIUserActivityRestoring]?) -> Void
  ) -> Bool {
    let result = RCTLinkingManager.application(application, continue: userActivity, restorationHandler: restorationHandler)
    return super.application(application, continue: userActivity, restorationHandler: restorationHandler) || result
  }
}

${reactNativeDelegate}
`;

// Generated by Expo SDK 58 prebuild: URLs reach the AppDelegate through ExpoAppSceneDelegate,
// and the template no longer overrides the URL or user-activity callbacks.
const expo58AppDelegate = `internal import Expo
import React
import ReactAppDependencyProvider

@main
class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider {
  var window: UIWindow?

  var reactNativeDelegate: ExpoReactNativeFactoryDelegate?
  var reactNativeFactory: RCTReactNativeFactory?

  public override func application(
    _ application: UIApplication,
    didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]? = nil
  ) -> Bool {
    let delegate = ReactNativeDelegate()
    let factory = ExpoReactNativeFactory(delegate: delegate)
    delegate.dependencyProvider = RCTAppDependencyProvider()

    reactNativeDelegate = delegate
    reactNativeFactory = factory

    // The window is created and React Native is started by \`SceneDelegate\` under the
    // scene-based life cycle (required by the iOS 27 SDK).
    return super.application(application, didFinishLaunchingWithOptions: launchOptions)
  }
}

${reactNativeDelegate}
`;

const appDelegateClass = (contents: string): string =>
  contents.slice(contents.indexOf('class AppDelegate'), contents.indexOf('class ReactNativeDelegate'));

const count = (contents: string, pattern: string): number => contents.split(pattern).length - 1;

const publicAppDelegate = expo56AppDelegate.replace(
  'class AppDelegate: ExpoAppDelegate',
  'public class AppDelegate: ExpoAppDelegate'
);

describe('applyExpoAppDelegatePatch', () => {
  it('adds AppAuth conformance to Expo 56 Swift AppDelegate templates', () => {
    const result = applyExpoAppDelegatePatch(expo56AppDelegate);

    expect(result).toContain('class AppDelegate: ExpoAppDelegate, RNAppAuthAuthorizationFlowManager {');
    expect(result).toContain(
      'public weak var authorizationFlowManagerDelegate: RNAppAuthAuthorizationFlowManagerDelegate?'
    );
    expect(result).toContain('authorizationFlowManagerDelegate.resumeExternalUserAgentFlow(with: url)');
  });

  it('preserves older public Swift AppDelegate templates', () => {
    const result = applyExpoAppDelegatePatch(publicAppDelegate);

    expect(result).toContain('public class AppDelegate: ExpoAppDelegate, RNAppAuthAuthorizationFlowManager {');
  });

  it('preserves existing protocol conformances', () => {
    const result = applyExpoAppDelegatePatch(
      expo56AppDelegate.replace(
        'class AppDelegate: ExpoAppDelegate',
        'class AppDelegate: ExpoAppDelegate, UIApplicationDelegate'
      )
    );

    expect(result).toContain(
      'class AppDelegate: ExpoAppDelegate, UIApplicationDelegate, RNAppAuthAuthorizationFlowManager {'
    );
  });

  it('preserves whitespace before the class opening brace', () => {
    const result = applyExpoAppDelegatePatch(
      expo56AppDelegate.replace(
        'class AppDelegate: ExpoAppDelegate {',
        `class AppDelegate: ExpoAppDelegate,
  UIApplicationDelegate
{`
      )
    );

    expect(result).toContain(`class AppDelegate: ExpoAppDelegate,
  UIApplicationDelegate, RNAppAuthAuthorizationFlowManager
{`);
  });

  it('does not duplicate an existing multiline AppAuth delegate property', () => {
    const appDelegateWithMultilineProperty = expo56AppDelegate.replace(
      '  var reactNativeFactory: RCTReactNativeFactory?',
      `  var reactNativeFactory: RCTReactNativeFactory?

  public weak var authorizationFlowManagerDelegate:
    RNAppAuthAuthorizationFlowManagerDelegate?`
    );

    const result = applyExpoAppDelegatePatch(appDelegateWithMultilineProperty);

    expect(result.match(/\bvar\s+authorizationFlowManagerDelegate\b/g)).toHaveLength(1);
  });

  it('is idempotent', () => {
    const once = applyExpoAppDelegatePatch(expo56AppDelegate);
    const twice = applyExpoAppDelegatePatch(once);

    expect(twice).toBe(once);
  });

  it('patches the Expo SDK 57 URL callbacks in place', () => {
    const result = applyExpoAppDelegatePatch(expo57AppDelegate);
    const delegateClass = appDelegateClass(result);

    expect(delegateClass).toContain(
      'class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider, RNAppAuthAuthorizationFlowManager {'
    );
    expect(count(result, 'override func application(')).toBe(3);
    expect(count(result, 'resumeExternalUserAgentFlow(with: url)')).toBe(1);
    expect(count(result, 'resumeExternalUserAgentFlow(with: webpageURL)')).toBe(1);
    expect(result.indexOf('resumeExternalUserAgentFlow(with: url)')).toBeLessThan(
      result.indexOf('return super.application(app, open: url, options: options) || RCTLinkingManager')
    );
    expect(result.indexOf('resumeExternalUserAgentFlow(with: webpageURL)')).toBeLessThan(
      result.indexOf('let result = RCTLinkingManager.application(application, continue:')
    );
    expect(applyExpoAppDelegatePatch(result)).toBe(result);
  });

  it('adds the URL callbacks to the Expo SDK 58 AppDelegate, which has none', () => {
    const result = applyExpoAppDelegatePatch(expo58AppDelegate);
    const delegateClass = appDelegateClass(result);

    expect(delegateClass).toContain(
      'class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider, RNAppAuthAuthorizationFlowManager {'
    );
    expect(delegateClass).toContain(
      'public weak var authorizationFlowManagerDelegate: RNAppAuthAuthorizationFlowManagerDelegate?'
    );
    expect(delegateClass).toContain(`  public override func application(
    _ app: UIApplication,
    open url: URL,
    options: [UIApplication.OpenURLOptionsKey: Any] = [:]
  ) -> Bool {
    if let authorizationFlowManagerDelegate = self.authorizationFlowManagerDelegate {
      if authorizationFlowManagerDelegate.resumeExternalUserAgentFlow(with: url) {
        return true
      }
    }

    return super.application(app, open: url, options: options)
  }`);
    expect(delegateClass).toContain(`  public override func application(
    _ application: UIApplication,
    continue userActivity: NSUserActivity,
    restorationHandler: @escaping ([UIUserActivityRestoring]?) -> Void
  ) -> Bool {
    if userActivity.activityType == NSUserActivityTypeBrowsingWeb,
      let webpageURL = userActivity.webpageURL,
      let authorizationFlowManagerDelegate = self.authorizationFlowManagerDelegate,
      authorizationFlowManagerDelegate.resumeExternalUserAgentFlow(with: webpageURL) {
      return true
    }

    return super.application(application, continue: userActivity, restorationHandler: restorationHandler)
  }
}`);
    expect(count(result, 'override func application(')).toBe(3);
    expect(result.endsWith(`}\n\n${reactNativeDelegate}\n`)).toBe(true);
    expect(applyExpoAppDelegatePatch(result)).toBe(result);
  });

  it('finds the end of the AppDelegate class past braces in comments and strings', () => {
    const withBraces = expo58AppDelegate.replace(
      '  var window: UIWindow?',
      `  var window: UIWindow? // }
  /* } */
  let closingBrace = "}\\"}"`
    );

    const result = applyExpoAppDelegatePatch(withBraces);

    expect(appDelegateClass(result)).toContain('continue userActivity: NSUserActivity');
    expect(result.endsWith(`}\n\n${reactNativeDelegate}\n`)).toBe(true);
  });

  it('fails when there is no Expo AppDelegate class to add the URL callbacks to', () => {
    expect(() =>
      applyExpoAppDelegatePatch(expo58AppDelegate.replace('class AppDelegate: ExpoAppDelegate', 'class AppDelegate: UIResponder'))
    ).toThrow('could not find the Expo AppDelegate class');
  });
});
